#include<stdio.h>
#include<math.h>


int main(void)
{
	float h, v, a, b;
	printf("Height of the dam: ");
	scanf("%f", &h);//h=height
	
	printf("Flow rate of water: ");
	scanf("%f*10^%f",&a, &b);
	v = a*pow(10, b);//v=flow rate of water
	
	float m, g, work, p;
	
	m = v * 1000;
	g = 9.80;

	work = m * g * h;
	p = (0.9 * work) / 1000000;//p=power

	printf("Predicted power generated by the hydroelectric dam: %.2f megawatts\n",p); 
	
}
